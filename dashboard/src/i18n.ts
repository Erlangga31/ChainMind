export function translate(language: Language, key: string): string {
  return (language === "id" ? indonesian : english)[key] ?? key;
}

export function formatNotification(
  language: Language,
  component: string,
  delayDays: number,
  coverageDays: number,
  vendor: string,
  totalPrice: string,
): string {
  return language === "id"
    ? `Bahan baku ${component} terlambat ${delayDays} hari. Stok cukup untuk ${coverageDays} hari (sumber: SAP S/4HANA). Rekomendasi: beli dari ${vendor} seharga ${totalPrice} (sumber: SAP Ariba).`
    : `Raw material ${component} delayed ${delayDays} days. Stock for ${coverageDays} days (source: SAP S/4HANA). Recommendation: buy from ${vendor} at ${totalPrice} (source: SAP Ariba).`;
}
